fn into_mersenne31_constants(constants: &[u32]) -> Vec<Mersenne31> {
    constants
        .iter()
        .copied()
        .map(Mersenne31::from_u32)
        .collect()
}

/// Reproduce the reference implementation's `_init_cons` derivation.
///
/// Each constant consumes `ceil(bits(p) / 8) + 1` little-endian bytes from a
/// SHAKE256 stream and is reduced modulo `p`. The instance-specific seed keeps
/// the BabyBear and KoalaBear constants distinct at both target widths.
fn derive_round_constants<F: PrimeField>(t: usize) -> Vec<F> {
    let modulus = F::modulus();
    let seed = format!("pSquare-hash({modulus},{t},{PSQUAREHASH_ROUNDS})aff");
    let mut shake = Shake256::default();
    shake.update(seed.as_bytes());
    let mut reader = shake.finalize_xof();
    let draw_bytes = (modulus.bits() as usize).div_ceil(8) + 1;

    (0..t / 2 * PSQUAREHASH_ROUNDS)
        .map(|_| {
            let mut bytes = [0u8; 16];
            reader.read(&mut bytes[..draw_bytes]);
            F::from_biguint(&BigUint::from_bytes_le(&bytes[..draw_bytes]))
        })
        .collect()
}

